/**
 * Cloudflare Worker entry: runs in front of the OpenNext handler.
 *
 * It does what src/proxy.ts did on Vercel. Next 16 proxies run on Node.js,
 * which OpenNext only supports experimentally on Workers, so the two jobs
 * live here instead:
 *
 *   1. Canonical host — www.algo-thinker.com → algo-thinker.com (308), so
 *      cookies set on the apex are always sent (the Google OAuth callback is
 *      registered on the apex).
 *   2. Route gate — protected pages without a session cookie redirect to
 *      /login, protected APIs get 401. This is defense-in-depth only: every
 *      protected page and route checks the session in D1 itself via
 *      getAuthContext().
 */
import type { ExecutionContext } from "@cloudflare/workers-types";
// @ts-ignore -- generated by `opennextjs-cloudflare build`
import { default as handler } from "./.open-next/worker.js";

const CANONICAL_HOST = "algo-thinker.com";
const SESSION_COOKIE = "algoads_session";

function isProtectedPath(pathname: string): boolean {
  if (pathname === "/login" || pathname === "/signup") return false;
  if (pathname.startsWith("/api/auth/")) return false;
  if (pathname.startsWith("/api/oauth/")) return false;

  return (
    pathname.startsWith("/campaigns") ||
    pathname.startsWith("/launch") ||
    pathname.startsWith("/api/campaigns") ||
    pathname.startsWith("/api/creative")
  );
}

function hasSessionCookie(req: Request): boolean {
  const cookie = req.headers.get("cookie") ?? "";
  return cookie.split(";").some((c) => {
    const [name, ...rest] = c.trim().split("=");
    return name === SESSION_COOKIE && rest.join("=").length > 0;
  });
}

export default {
  async fetch(req: Request, env: CloudflareEnv, ctx: ExecutionContext): Promise<Response> {
    const url = new URL(req.url);

    if (url.hostname === `www.${CANONICAL_HOST}`) {
      url.hostname = CANONICAL_HOST;
      return Response.redirect(url.toString(), 308);
    }

    if (isProtectedPath(url.pathname) && !hasSessionCookie(req)) {
      if (url.pathname.startsWith("/api/")) {
        return Response.json({ error: "unauthorized" }, { status: 401 });
      }
      const login = new URL("/login", url);
      login.searchParams.set("next", url.pathname + url.search);
      return Response.redirect(login.toString(), 307);
    }

    return handler.fetch(req, env, ctx);
  },
};
